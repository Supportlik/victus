    def passkeys_for_user(self, user_id: str) -> Sequence[orm.PasskeyCredential]: ...

    def delete_passkey(self, credential: orm.PasskeyCredential) -> None: ...

    def add_session(self, session: orm.Session) -> orm.Session: ...

