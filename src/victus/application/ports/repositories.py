"""Repository ports.

The ports are typed against the persistence models re-exported by
``victus.infrastructure.db.orm`` because the application layer works with the
mapped entities directly (a pragmatic choice documented in ADR 0001: the
domain layer stays framework-free; the application layer may see mapped
objects). Only the signatures the use cases need are declared here.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from datetime import date, datetime
from typing import TYPE_CHECKING, Any, Protocol

from victus.domain.values import Macros, TrainingType

if TYPE_CHECKING:
    from victus.infrastructure.db import orm


class TenantRepository(Protocol):
    def get(self, tenant_id: str) -> orm.Tenant | None: ...

    def get_by_slug(self, slug: str) -> orm.Tenant | None: ...

    def add(self, tenant: orm.Tenant) -> orm.Tenant: ...

    def list(self) -> Sequence[orm.Tenant]: ...


